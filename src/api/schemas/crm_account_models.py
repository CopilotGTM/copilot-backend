_ACCOUNT_OWNER_FIELDS = {"owner.id", "owner.name", "owner.email"}
_ACCOUNT_GENERATED_FIELDS = {
    "account_summary.status",
    "account_summary.content",
    "account_summary.last_researched_at",
}


def _account_field_edit_metadata(key: str) -> dict[str, Any]:
    if key in _ALWAYS_EDITABLE_ACCOUNT_FIELDS:
        patch_field, edit_control = _ALWAYS_EDITABLE_ACCOUNT_FIELDS[key]
        return {
            "editable": True,
            "patch_field": patch_field,
            "edit_control": edit_control,
            "edit_policy": "always",
            "locked_reason": None,
        }

    if key in _ACCOUNT_OWNER_FIELDS:
        return {
            "editable": False,
            "patch_field": None,
            "edit_control": None,
            "edit_policy": "assignment_action",
            "locked_reason": "Use an account owner assignment action.",
        }

    if key in _ACCOUNT_GENERATED_FIELDS:
        return {
            "editable": False,
            "patch_field": None,
            "edit_control": None,
            "edit_policy": "generated",
            "locked_reason": "Generated by account research.",
        }

    return {
        "editable": False,
        "patch_field": None,
        "edit_control": None,
        "edit_policy": "read_only",
        "locked_reason": "Read-only field.",
    }


def account_detail_field_definitions() -> list[AccountDetailFieldDefinition]:
    """Return ordered metadata for predefined account detail fields."""
    return [
        AccountDetailFieldDefinition(
            key=key,
            label=label,
            data_type=data_type,
            order=order,
            section=section,
            filter_control=filter_control,
            **_account_field_edit_metadata(key),
        )
        for key, label, data_type, order, section, filter_control in _ACCOUNT_DETAIL_FIELD_ROWS
    ]


