class CreateAccountRequest(BaseModel):
    """Payload for creating an internal account from CRM UI or tools."""

    name: str | None = None
    domain: str | None = None
    website: str | None = None
    industry: str | None = None
    linkedin_url: str | None = None

    @field_validator("name", mode="before")
    @classmethod
    def validate_name(cls, value: Any) -> Any:
        """Normalize blank account names to missing so identity validation is consistent."""
        if value is None:
            return None
        if not isinstance(value, str):
            return value
        cleaned = value.strip()
        return cleaned or None

    @model_validator(mode="after")
    def validate_identity(self) -> CreateAccountRequest:
        """Require at least one stable account identity before creating a row."""
        if self.name:
            return self
        if self.domain and self.domain.strip():
            return self
        if self.website and self.website.strip():
            return self
        raise ValueError("name, domain, or website is required")


