class _FakeScalarResult:
    """Lightweight object matching SQLAlchemy scalar result shape used in tests."""

    def __init__(self, rows: list[object]):
        """Capture a predetermined scalar list for deterministic assertions."""
        self._rows = rows

    def all(self) -> list[object]:
        """Return all rows exactly as the tested code expects to receive."""
        return self._rows

    def first(self) -> object | None:
        """Return the first row for code paths that check single-result presence."""
        return self._rows[0] if self._rows else None


class _FakeExecuteResult:
    """Mimic the subset of SQLAlchemy execute result APIs used in this test."""

    def __init__(self, rows: list[object]):
        """Store a predefined row payload for controlled query simulation."""
        self._rows = rows

    def scalars(self) -> _FakeScalarResult:
        """Expose a scalar result accessor so query handlers can iterate rows."""
        return _FakeScalarResult(self._rows)

    def scalar_one_or_none(self) -> object | None:
        """Expose the first-row accessor used by idempotency lookup assertions."""
        return self._rows[0] if self._rows else None


class _FakeSession:
    """Fake SQLAlchemy session that captures statements without external dependencies."""

    def __init__(
        self, *, get_result: object | None = None, execute_rows: list[object] | None = None
    ):
        """Capture the configured query results and side effects."""
        self.get_result = get_result
        self.execute_rows = execute_rows or []
        self.added: list[object] = []
        self.executed_statements: list[object] = []
        self.flushed = False
        self.refreshed: list[object] = []

    async def get(self, model: object, entity_id: object) -> object | None:
        """Return the injected row for entity lookups."""
        return self.get_result

    async def execute(self, statement: object) -> _FakeExecuteResult:
        """Record SQL generated by the service and return configured rows."""
        self.executed_statements.append(statement)
        return _FakeExecuteResult(self.execute_rows)

    def add(self, obj: object) -> None:
        """Capture objects written by service methods."""
        self.added.append(obj)

    async def flush(self) -> None:
        """Mark flush as called, matching Unit of Work behavior used by callers."""
        self.flushed = True

    async def refresh(self, obj: object) -> None:
        """Track refreshed rows to assert post-write materialization."""
        self.refreshed.append(obj)


def _deal(*, organisation_id):
    """Create a minimal CRM deal stub for automation service calls."""
    return SimpleNamespace(
        deal_id=uuid4(),
        organisation_id=organisation_id,
        external_id="deal-ext-1",
        name="Acme Expansion",
        is_deleted=False,
    )


def _task(*, organisation_id, deal_id, integration_id=None, status="NOT_STARTED") -> CRMActivity:
    """Create a minimal CRM task stub with defaults for completion/list tests."""
    return CRMActivity(
        activity_id=uuid4(),
        organisation_id=organisation_id,
        integration_id=integration_id,
        external_id=str(uuid4()),
        activity_type=CRMActivityType.TASK.value,
        status=status,
        subject="Send pricing proposal",
        deal_id=deal_id,
        source=CRMActivitySource.AI_MEETING.value,
        properties={},
    )


@pytest.mark.asyncio
async def test_list_deal_tasks_scopes_query_to_org_deal_and_task_types() -> None:
    """List tasks must filter by org, deal and task type, never returning other rows."""
    # Scope:
    # 1) Build one task that matches the target org/deal.
    # 2) Run listing and verify SQL includes each required filter.
    organisation_id = uuid4()
    deal_id = uuid4()
    existing_task = _task(organisation_id=organisation_id, deal_id=deal_id)
    session = _FakeSession(execute_rows=[existing_task])
    service = DealTaskAutomationService(session, organisation_id)

    tasks = await service.list_deal_tasks(deal_id)

    assert tasks == [existing_task]
    assert len(session.executed_statements) == 1
    statement_sql = str(session.executed_statements[0])
    assert "crm_activities.organisation_id" in statement_sql
    assert "crm_activities.deal_id" in statement_sql
    assert "crm_activities.activity_type" in statement_sql


@pytest.mark.asyncio
async def test_create_ai_meeting_task_with_resolved_owner() -> None:
    """Create should persist a task with resolved assignee metadata when owner is known."""
    # Arrange: wire deterministic service outputs so only the create-task happy path is exercised.
    organisation_id = uuid4()
    deal = _deal(organisation_id=organisation_id)
    owner_id = uuid4()
    event_id = uuid4()
    association_id = uuid4()
    job_id = uuid4()
    session = _FakeSession()
    service = DealTaskAutomationService(session, organisation_id)
    service._load_deal = AsyncMock(return_value=deal)  # type: ignore[method-assign]
    service._find_existing_task = AsyncMock(return_value=None)  # type: ignore[method-assign]
    service._resolve_assignee = AsyncMock(  # type: ignore[method-assign]
        return_value=(
            owner_id,
            "Alex Morgan",
            "alex@example.com",
            {"status": "resolved", "input": "alex@example.com", "match": "email"},
        )
    )

    result = await service.create_task(
        deal_id=deal.deal_id,
        subject="Send pricing proposal",
        body="Follow up with the revised commercial proposal.",
        assignee_name_or_email="alex@example.com",
        source_event_id=event_id,
        source_association_id=association_id,
        source_summary_job_id=job_id,
        priority=CRMActivityPriority.HIGH.value,
    )

    assert result.created is True
    assert result.reason is None
    task = result.task
    assert task in session.added
    assert task.subject == "Send pricing proposal"
    assert task.body == "Follow up with the revised commercial proposal."
    assert task.source == CRMActivitySource.AI_MEETING.value
    assert task.priority == CRMActivityPriority.HIGH.value
    assert task.status == CRMActivityStatus.NOT_STARTED.value
    assert task.deal_id == deal.deal_id
    assert task.related_local_id == deal.deal_id
    assert task.related_name == deal.name
    assert task.owner_id is None
    assert task.owner_external_id == str(owner_id)
    assert task.owner_name == "Alex Morgan"
    assert task.owner_email == "alex@example.com"
    assert task.properties["created_via"] == "deal_task_agent"
    assert task.properties["source_event_id"] == str(event_id)
    assert task.properties["source_association_id"] == str(association_id)
    assert task.properties["source_summary_job_id"] == str(job_id)
    assert task.properties["assignee_resolution"]["status"] == "resolved"
    assert task.properties["idempotency_key"]


