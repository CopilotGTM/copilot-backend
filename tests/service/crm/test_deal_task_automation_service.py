@pytest.mark.asyncio
async def test_complete_task_marks_internal_task_completed() -> None:
    """Complete should update status and timestamps only for internal same-org tasks."""
    # This path verifies both contract fields and that a successful write path flushes state.
    organisation_id = uuid4()
    deal_id = uuid4()
    task = _task(organisation_id=organisation_id, deal_id=deal_id)
    session = _FakeSession(get_result=task)
    service = DealTaskAutomationService(session, organisation_id)

    completed = await service.complete_task(
        task.activity_id,
        deal_id=deal_id,
        completion_reason="The proposal was sent during the follow-up.",
    )

    assert completed is task
    assert task.status == CRMActivityStatus.COMPLETED.value
    assert task.completed_date is not None
    assert task.properties["completed_via"] == "deal_task_agent"
    assert task.properties["completion_reason"] == "The proposal was sent during the follow-up."
    assert session.flushed is True
    assert session.refreshed == [task]


@pytest.mark.asyncio
async def test_complete_task_refuses_crm_synced_activity() -> None:
    """Complete must reject CRM-synced tasks to prevent external-data corruption."""
    # `integration_id` indicates source sync ownership; automation cannot complete it.
    organisation_id = uuid4()
    deal_id = uuid4()
    task = _task(organisation_id=organisation_id, deal_id=deal_id, integration_id=uuid4())
    session = _FakeSession(get_result=task)
    service = DealTaskAutomationService(session, organisation_id)

    with pytest.raises(DealTaskAutomationError) as exc:
        await service.complete_task(
            task.activity_id,
            deal_id=deal_id,
            completion_reason="The summary says this was completed.",
        )

    assert exc.value.status_code == 409
    assert exc.value.message == "External CRM tasks are read-only"
    assert task.status == CRMActivityStatus.NOT_STARTED.value


